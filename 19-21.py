# Одна куча
def g(s, p):
    # Указываем условие победы (например, куча >= 88)
    if s >= 88:
        return p == 2 or p == 4  # победа на 2-м или 4-м ходу (Петя/Ваня в зависимости от задачи)
    if p == 5:  # Максимальная глубина дерева ходов
        return 0

    # Список возможных ходов (например, +1 или *2)
    moves = [g(s + 1, p + 1), g(s * 2, p + 1)]

    # Логика для 20 задания (победа Пети первым или вторым ходом)
    if p % 2 == 1:  # Ход Пети (номер хода нечетный)
        return any(moves)
    else:  # Ход Вани (номер хода четный)
        # Если Ваня должен выиграть своим ходом или в зависимости от условий
        return any(moves)  # или all(moves) в зависимости от формулировки


# Поиск ответа для заданий 19, 20, 21
print('19:', [s for s in range(1, 88) if g(s, 1)])
print('20:', [s for s in range(1, 88) if not g(s, 1) and g(s, 3)])
print('21:', [s for s in range(1, 88) if not g(s, 1) and g(s, 4)])

# Две кучи
def g(s1, s2, p):
    # Условие победы (например, сумма камней >= 87)
    if s1 + s2 >= 87:
        return p == 2 or p == 4
    if p == 5:
        return 0

    # Возможные ходы для двух куч
    moves = [
        g(s1 + 1, s2, p + 1),
        g(s1, s2 + 1, p + 1),
        g(s1 * 2, s2, p + 1),
        g(s1, s2 * 2, p + 1),
    ]

    if p % 2 == 1:
        return any(moves)
    else:
        return any(moves)  # Вариант с any/all зависит от точных требований задачи


# Начальное количество камней в первой куче фиксировано (например, 7), а во второй меняется
S1 = 7
print('19:', [s2 for s2 in range(1, 80) if g(S1, s2, 1)])
print('20:', [s2 for s2 in range(1, 80) if not g(S1, s2, 1) and g(S1, s2, 3)])
print('21:', [s2 for s2 in range(1, 80) if not g(S1, s2, 1) and g(S1, s2, 4)])
